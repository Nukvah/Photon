"""Photon launcher icon: a bold icosahedron over two rings of dots, on a 108-unit adaptive-icon grid.

Writes store/icon.svg and the Android vector drawables (foreground and monochrome) into the
given folder; move the two .xml files to app/src/main/res/drawable/.
Only lines and circles, so it maps 1:1 to a VectorDrawable.
"""
import math, sys

CX, CY, R = 54, 44, 25        # orb (inside the 66-unit safe circle)
WY, TILT = 57, 0.45             # water ring centre and flattening
RINGS = [(28, 20, 2.4, 1.0), (37, 28, 1.8, 0.55)]   # radius, dot count, dot radius, alpha
BG = "#0B0E14"

t = (1 + 5 ** 0.5) / 2
V = [(-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0), (0, -1, t), (0, 1, t), (0, -1, -t), (0, 1, -t),
     (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1)]
L = math.sqrt(1 + t * t)
V = [(x / L, y / L, z / L) for x, y, z in V]
E = [(a, b) for a in range(12) for b in range(a + 1, 12)
     if abs(sum((V[a][i] - V[b][i]) ** 2 for i in range(3)) - (2 / L) ** 2) < 1e-6]

def rot(v, ax, ay):
    x, y, z = v
    x, z = x * math.cos(ay) + z * math.sin(ay), -x * math.sin(ay) + z * math.cos(ay)
    y, z = y * math.cos(ax) - z * math.sin(ax), y * math.sin(ax) + z * math.cos(ax)
    return x, y, z
P = [rot(v, 0.70, 0.0) for v in V]   # a vertex near the front: reads as a gem at any size
pt = lambda p: (CX + p[0] * R, CY + p[1] * R)

front = [e for e in E if (P[e[0]][2] + P[e[1]][2]) / 2 > -0.05]
back = [e for e in E if e not in front]

def ring_dots():
    out = []
    for r, n, s, a in RINGS:
        for i in range(n):
            ang = 2 * math.pi * (i + 0.5) / n
            x, y = CX + r * math.cos(ang), WY + r * math.sin(ang) * TILT
            if math.sin(ang) < 0.25:
                continue  # only the near half of each ripple, so it reads as an arc under the orb
            if math.hypot(x - 54, y - 54) > 33:
                continue  # keep inside the adaptive icon's safe circle
            size = s * (0.8 + 0.35 * max(0, math.sin(ang)))   # nearer dots a bit bigger
            out.append((x, y, size, a * (0.55 + 0.45 * max(0, math.sin(ang)))))
    return out
DOTS = ring_dots()

def svg(size, bg=True, color="#FFFFFF", glow="#8FA8FF"):
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="{size}" height="{size}">']
    if bg:
        o.append(f'<rect width="108" height="108" fill="{BG}"/>')
    for x, y, s, a in DOTS:
        o.append(f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{s:.2f}" fill="{color}" fill-opacity="{a:.2f}"/>')
    for a, b in back:
        (x1, y1), (x2, y2) = pt(P[a]), pt(P[b])
        o.append(f'<line x1="{x1:.2f}" y1="{y1:.2f}" x2="{x2:.2f}" y2="{y2:.2f}" stroke="{color}" stroke-opacity="0.3" stroke-width="1.2" stroke-linecap="round"/>')
    for a, b in front:
        (x1, y1), (x2, y2) = pt(P[a]), pt(P[b])
        o.append(f'<line x1="{x1:.2f}" y1="{y1:.2f}" x2="{x2:.2f}" y2="{y2:.2f}" stroke="{glow}" stroke-opacity="0.35" stroke-width="4.5" stroke-linecap="round"/>')
    for a, b in front:
        (x1, y1), (x2, y2) = pt(P[a]), pt(P[b])
        o.append(f'<line x1="{x1:.2f}" y1="{y1:.2f}" x2="{x2:.2f}" y2="{y2:.2f}" stroke="{color}" stroke-width="2.4" stroke-linecap="round"/>')
    o.append('</svg>')
    return "\n".join(o)

def path_lines(edges):
    return "".join(f"M{pt(P[a])[0]:.2f},{pt(P[a])[1]:.2f}L{pt(P[b])[0]:.2f},{pt(P[b])[1]:.2f}" for a, b in edges)

def circle(x, y, r):
    return f"M{x - r:.2f},{y:.2f}a{r:.2f},{r:.2f} 0,1 0,{2 * r:.2f},0a{r:.2f},{r:.2f} 0,1 0,{-2 * r:.2f},0Z"

def drawable(mono):
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<!-- Launcher icon: a photon (an icosahedron of light) over rippling water. Generated by store/icon.py. -->',
         '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
         '    android:width="108dp"', '    android:height="108dp"',
         '    android:viewportWidth="108"', '    android:viewportHeight="108">']
    for x, y, s, a in DOTS:
        o.append(f'    <path android:fillColor="#FFFFFF" android:fillAlpha="{1 if mono else round(a, 2)}" android:pathData="{circle(x, y, s)}" />')
    o.append(f'    <path android:strokeColor="#FFFFFF" android:strokeAlpha="0.3" android:strokeWidth="1.2" android:strokeLineCap="round" android:pathData="{path_lines(back)}" />')
    if not mono:
        o.append(f'    <path android:strokeColor="#8FA8FF" android:strokeAlpha="0.35" android:strokeWidth="4.5" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{path_lines(front)}" />')
    o.append(f'    <path android:strokeColor="#FFFFFF" android:strokeWidth="2.4" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{path_lines(front)}" />')
    o.append('</vector>')
    return "\n".join(o) + "\n"

if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "store"
    open(f"{out}/icon.svg", "w").write(svg(108))
    open(f"{out}/ic_launcher_foreground.xml", "w").write(drawable(False))
    open(f"{out}/ic_launcher_monochrome.xml", "w").write(drawable(True))
