"""Photon launcher icon: a light wave that ends in a particle (wave-particle duality), two colours on soft white,
on a 108-unit adaptive-icon grid.

Writes store/icon.svg and the Android vector drawables (launcher foreground, monochrome and the in-app logo)
into the given folder; move the .xml files to app/src/main/res/drawable/.
Only one stroked path and one circle, so it maps 1:1 to a VectorDrawable.
"""
import math, sys

BG = "#FAF7F2"       # soft white (also @color/ic_launcher_background)
WAVE = "#2E3A8C"     # indigo
DOT = "#F5A623"      # amber
X0, STEP, N = 29, 0.33, 100          # wave from x=29 to x=62
CY, AMP, CYCLES = 54, 6.5, 1.5
WIDTH = 5.5
DOT_X, DOT_R = 72, 9                 # everything stays inside the 66-unit safe circle

def wave_points():
    pts = []
    for i in range(0, N + 1, 2):
        amp = AMP * (1 - i / N * 0.15)
        pts.append((X0 + i * STEP, CY - amp * math.sin(i / N * 2 * math.pi * CYCLES)))
    return pts

def wave_path(dx=0.0, dy=0.0):
    p = wave_points()
    return f"M{p[0][0] + dx:.2f},{p[0][1] + dy:.2f}" + "".join(f"L{x + dx:.2f},{y + dy:.2f}" for x, y in p[1:])

def circle(x, y, r):
    return f"M{x - r:.2f},{y:.2f}a{r:.2f},{r:.2f} 0,1 0,{2 * r:.2f},0a{r:.2f},{r:.2f} 0,1 0,{-2 * r:.2f},0Z"

def svg(size):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="{size}" height="{size}">\n'
            f'<rect width="108" height="108" fill="{BG}"/>\n'
            f'<path d="{wave_path()}" fill="none" stroke="{WAVE}" stroke-width="{WIDTH}" stroke-linecap="round" stroke-linejoin="round"/>\n'
            f'<circle cx="{DOT_X}" cy="{CY}" r="{DOT_R}" fill="{DOT}"/>\n</svg>\n')

def vector(comment, w, h, vw, vh, wave_color, dot_color, dx=0.0, dy=0.0):
    return "\n".join([
        '<?xml version="1.0" encoding="utf-8"?>',
        f'<!-- {comment} Generated by store/icon.py. -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{w}dp"', f'    android:height="{h}dp"',
        f'    android:viewportWidth="{vw}"', f'    android:viewportHeight="{vh}">',
        f'    <path android:strokeColor="{wave_color}" android:strokeWidth="{WIDTH}" android:strokeLineCap="round" '
        f'android:strokeLineJoin="round" android:pathData="{wave_path(dx, dy)}" />',
        f'    <path android:fillColor="{dot_color}" android:pathData="{circle(DOT_X + dx, CY + dy, DOT_R)}" />',
        '</vector>', ''])

if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "store"
    open(f"{out}/icon.svg", "w").write(svg(108))
    desc = "Launcher icon: a light wave that ends in a photon."
    open(f"{out}/ic_launcher_foreground.xml", "w").write(vector(desc, 108, 108, 108, 108, WAVE, DOT))
    open(f"{out}/ic_launcher_monochrome.xml", "w").write(vector(desc, 108, 108, 108, 108, "#FFFFFF", "#FFFFFF"))
    # In-app logo next to the app name: the same mark cropped to its bounds (x 26..81, y 45..63 plus margin).
    x0, y0, vw, vh = 25.5, 44, 56, 20
    open(f"{out}/ic_logo.xml", "w").write(
        vector("In-app logo: the launcher mark without its background.", 42, 15, vw, vh, WAVE, DOT, -x0, -y0))
